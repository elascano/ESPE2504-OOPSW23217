    private void btnUploadDataActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUploadDataActionPerformed
        VegicleRepository soundMixerRepository = new VegicleRepository();
        soundMixerRepository.createVehicle(
                txtBrand.getText(),
                txtModel.getText(),
                comboSystemType.getSelectedItem().equals("Digital"),
                Integer.parseInt(txtChannelCount.getText()),
                Float.parseFloat(txtPrice.getText()),
                txtSerialNumber.getText()
        );
    }//GEN-LAST:event_btnUploadDataActionPerformed

    private void btnDeleteDataActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteDataActionPerformed
        VehicleDeleteRepository vehicleDeleteRepository = new VehicleDeleteRepository();
        vehicleDeleteRepository.deleteBySerialNumber(txtSerialNumber.getText());
    }//GEN-LAST:event_btnDeleteDataActionPerformed

    private void btnSearchDataActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSearchDataActionPerformed
        VehicleSearchRepository searchRepo = new VehicleSearchRepository();
        Vehicle mixer = searchRepo.findBySerialNumber(txtSerialNumber.getText());
        if (mixer != null) {
            txtBrand.setText(mixer.getBrand());
            txtModel.setText(mixer.getModel());
            comboSystemType.setSelectedItem(mixer.isIsDigital() ? "Digital" : "Analogico");
            txtChannelCount.setText(String.valueOf(mixer.getNumChannels()));
            precioUSDOriginal = mixer.getPrice(); // <-- Aquí actualizas el valor original en USD
            txtPrice.setText(String.valueOf(precioUSDOriginal)); // <-- Siempre muestra el precio en USD al buscar
            jComboBox1.setSelectedItem("USD"); // Opcional: fuerza a mostrar USD al buscar
        }
        }//GEN-LAST:event_btnSearchDataActionPerformed

    private void txtChannelCountKeyTyped(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_txtChannelCountKeyTyped
        int key = evt.getKeyChar();

        boolean numeros = key >= 48 && key <= 57;

        if (!numeros) {
            evt.consume();
        }

        if (txtChannelCount.getText().trim().length() == 10) {
            evt.consume();
        }
    }//GEN-LAST:event_txtChannelCountKeyTyped

    private void txtPriceKeyTyped(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_txtPriceKeyTyped
        int key = evt.getKeyChar();

        boolean esNumero = key >= '0' && key <= '9';
        boolean esPunto = key == '.';

        if (!esNumero && !esPunto) {
            evt.consume();
        } else if (esPunto && txtPrice.getText().contains(".")) {
            evt.consume();
        } else if (txtPrice.getText().trim().length() == 10) {
            evt.consume();
        }
    }//GEN-LAST:event_txtPriceKeyTyped

    private void btnUpdateDataActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateDataActionPerformed
        VegicleRepository soundMixerRepository = new VegicleRepository();
        float precioAEnviar = precioUSDOriginal; // Siempre en USD
        soundMixerRepository.updateSoundMixer(
                txtBrand.getText(),
                txtModel.getText(),
                comboSystemType.getSelectedItem().equals("Digital"),
                Integer.parseInt(txtChannelCount.getText()),
                precioAEnviar, // Envía el precio original en USD
                txtSerialNumber.getText()
        );
        javax.swing.JOptionPane.showMessageDialog(this, "Información actualizada correctamente.");
    }//GEN-LAST:event_btnUpdateDataActionPerformed

    private void jComboBox1ItemStateChanged(java.awt.event.ItemEvent evt) {//GEN-FIRST:event_jComboBox1ItemStateChanged
       if (evt.getStateChange() == java.awt.event.ItemEvent.SELECTED) {
            CurrencyConverter.updatePriceField(txtPrice, jComboBox1, precioUSDOriginal);
        }
    }//GEN-LAST:event_jComboBox1ItemStateChanged

